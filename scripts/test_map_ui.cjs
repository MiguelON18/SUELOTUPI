const assert=require('node:assert/strict');
const ui=require('../map-ui.js');
const layer={id:'C4_2025_AII_VISUAL',visible:true,style:{thematic:'mapbiomas'},classVisibility:{3:false,12:true}};
assert.equal(ui.featureVisible(layer,{properties:{'ID MapBiomas':3}}),false);
assert.equal(ui.featureVisible(layer,{properties:{'ID MapBiomas':12}}),true);
layer.visible=false;assert.equal(ui.featureVisible(layer,{properties:{'ID MapBiomas':12}}),false);
const contours={visible:true,style:{thematic:'contour'}};
assert.equal(ui.featureVisible(contours,{properties:{indice:false}},13),false);
assert.equal(ui.featureVisible(contours,{properties:{indice:true}},13),true);
assert.equal(ui.featureVisible(contours,{properties:{indice:false}},14),true);
const water={id:'CANALES_INTERPRETADOS',style:{}};
const rows=ui.featureRows(water,{properties:{Nombre:'A01 · amuna0',longitud_m:277.569,'Fecha de imagen':'05/11/2023',ID:'A01','Estado de revisión':'Delimitado por observación visual del grupo; función por confirmar'}});
assert(rows.length<=4);assert(rows.some(([k,v])=>k==='Longitud'&&v.includes('278')));
assert(rows.some(([k,v])=>k==='Imagen de referencia'&&v==='05/11/2023'));
assert(!rows.some(([k])=>['ID','Nombre original','Estado de revisión'].includes(k)));
const movement=ui.featureRows({id:'PUNTOS_REVISION_INVENTARIO',style:{}},{properties:{proceso_declarado_GDB:'Flujo de Detrito',fuente_declarada_GDB:'INGEMMET',objectid_heredado:23444,id_recorte:'tecnico'}});
assert(movement.length<=4);assert(movement.some(([k,v])=>v==='Flujo de Detrito'));
assert(!movement.some(([k])=>/objectid|recorte|latitud|longitud/.test(k)));
console.log('OK: clases visibles, detalle de curvas y fichas breves sin IDs técnicos');
