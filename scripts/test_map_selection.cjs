const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const mapUi=require('../map-ui.js');
const source=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
const polygon=[[0,0],[100,0],[100,100],[0,100],[0,0]];
const thematic={kind:'polygon',rings:[polygon],layer:{id:'C4',visible:true}};
const boundary={kind:'polygon',rings:[polygon],borderOnly:true,tolerance:6,layer:{id:'AII',visible:true}};
const context=vm.createContext({state:{hitIndex:[thematic,boundary]},clamp:(v,a,b)=>Math.max(a,Math.min(b,v))});
const hit=source.slice(source.indexOf('  function pointInRing('),source.indexOf('  function geometryCoords('));
vm.runInContext(hit,context);
assert.equal(vm.runInContext('hitTest(50,50).layer.id',context),'C4','el interior del ámbito permite consultar la temática');
assert.equal(vm.runInContext('hitTest(2,50).layer.id',context),'AII','el borde sigue abriendo ficha del límite');
let draws=0;
const selection={feature:{},layer:{visible:false}};
const drawContext=vm.createContext({mapUi,state:{selected:selection},ctx:{save(){},restore(){}},styleFor:()=>({}),drawGeometry:()=>draws++});
const draw=source.slice(source.indexOf('  function drawSelection('),source.indexOf('  function render('));
vm.runInContext(draw+'\ndrawSelection();',drawContext);
assert.equal(draws,0,'una capa apagada no debe seguir resaltada');
selection.layer.visible=true;
vm.runInContext('drawSelection();',drawContext);
assert.equal(draws,1);
selection.layer.style={thematic:'mapbiomas'};selection.layer.classVisibility={3:false};selection.feature.properties={'ID MapBiomas':3};
vm.runInContext('drawSelection();',drawContext);assert.equal(draws,1,'una clase apagada no conserva el resaltado');
console.log('OK: fichas temáticas bajo límites y selección de capas visibles');
